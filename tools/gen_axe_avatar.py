#!/usr/bin/env python3
"""Turn the supplied Q portrait into LVGL 9 RGB565A8 sprites.

The color plane is native little-endian RGB565. The alpha plane follows it,
with stride/2, which is how LVGL 9 draws LV_COLOR_FORMAT_RGB565A8.
Background pixels connected to the image edge are transparent. Output pixels
are nearest-neighbor samples so the portrait stays blocky on the 240x320 panel.
"""

from __future__ import annotations

import argparse
from collections import deque
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SRC = ROOT / "assets" / "images" / "axe-king-q.jpg"
SIZES = (64, 96)


def knock_out_background(image: Image.Image) -> Image.Image:
    image = image.convert("RGBA")
    width, height = image.size
    pixels = image.load()
    background = pixels[0, 0][:3]

    def is_background(color: tuple[int, int, int, int]) -> bool:
        return (
            abs(color[0] - background[0]) < 22
            and abs(color[1] - background[1]) < 22
            and abs(color[2] - background[2]) < 22
            and abs(color[0] - color[1]) < 12
            and abs(color[1] - color[2]) < 12
        )

    seen = bytearray(width * height)
    queue: deque[tuple[int, int]] = deque()
    for x in range(width):
        queue.append((x, 0))
        queue.append((x, height - 1))
    for y in range(height):
        queue.append((0, y))
        queue.append((width - 1, y))
    while queue:
        x, y = queue.popleft()
        index = y * width + x
        if seen[index]:
            continue
        seen[index] = 1
        color = pixels[x, y]
        if not is_background(color):
            continue
        pixels[x, y] = (0, 0, 0, 0)
        if x:
            queue.append((x - 1, y))
        if x + 1 < width:
            queue.append((x + 1, y))
        if y:
            queue.append((x, y - 1))
        if y + 1 < height:
            queue.append((x, y + 1))
    cropped = image.crop(image.getbbox())
    side = max(cropped.size)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(cropped, ((side - cropped.size[0]) // 2, (side - cropped.size[1]) // 2), cropped)
    return square


def sprite(square: Image.Image, size: int) -> Image.Image:
    out = square.resize((size, size), Image.Resampling.NEAREST)
    pixels = out.load()
    for y in range(size):
        for x in range(size):
            red, green, blue, alpha = pixels[x, y]
            if alpha < 24:
                pixels[x, y] = (0, 0, 0, 0)
            else:
                pixels[x, y] = (red & 0xF8, green & 0xFC, blue & 0xF8, 255)
    return out


def rgb565(red: int, green: int, blue: int) -> int:
    return ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)


def emit(path: Path, symbol: str, image: Image.Image) -> None:
    width, height = image.size
    pixels = image.load()
    color = bytearray()
    alpha = bytearray()
    for y in range(height):
        for x in range(width):
            red, green, blue, opacity = pixels[x, y]
            value = rgb565(red, green, blue) if opacity else 0
            color.append(value & 0xFF)
            color.append(value >> 8)
            alpha.append(opacity)
    blob = color + alpha
    lines = []
    for offset in range(0, len(blob), 16):
        chunk = ", ".join("0x%02X" % byte for byte in blob[offset:offset + 16])
        lines.append(f"    {chunk},")
    text = f"""/* Generated by tools/gen_axe_avatar.py. Do not edit by hand.
 * LVGL 9 RGB565A8, {width}x{height}, nearest-neighbor, edge background removed.
 * AXE_AVATAR_BYTES {len(blob)}
 */
#include "lvgl.h"

#ifndef LV_ATTRIBUTE_LARGE_CONST
#define LV_ATTRIBUTE_LARGE_CONST
#endif

static LV_ATTRIBUTE_LARGE_CONST const uint8_t {symbol}_map[] = {{
{chr(10).join(lines)}
}};

const lv_image_dsc_t {symbol} = {{
    .header.magic = LV_IMAGE_HEADER_MAGIC,
    .header.cf = LV_COLOR_FORMAT_RGB565A8,
    .header.flags = 0,
    .header.w = {width},
    .header.h = {height},
    .header.stride = {width * 2},
    .data_size = {len(blob)},
    .data = {symbol}_map,
}};
"""
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path} ({len(blob)} bytes)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", type=Path, default=DEFAULT_SRC)
    parser.add_argument("--symbol", default="axe_king_q")
    parser.add_argument("--sizes", default="64,96")
    args = parser.parse_args()
    square = knock_out_background(Image.open(args.src))
    out_dir = ROOT / "assets" / "images"
    out_dir.mkdir(parents=True, exist_ok=True)
    for size in (int(item) for item in args.sizes.split(",") if item):
        frame = sprite(square, size)
        frame.save(out_dir / f"{args.symbol.replace('_', '-')}-{size}.png")
        emit(out_dir / f"{args.symbol}_{size}.c", f"{args.symbol}_{size}", frame)


if __name__ == "__main__":
    main()
